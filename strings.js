export const LANGUAGES = ['en', 'vi'];

export function resolveLang(setting, currentLocale = '') {
    if (setting === 'en' || setting === 'vi') return setting;
    const locale = String(currentLocale ?? '').toLowerCase();
    for (const lang of LANGUAGES) {
        if (locale === lang || locale.startsWith(`${lang}-`)) return lang;
    }
    return 'en';
}

export function makeT(lang) {
    const table = STRINGS[lang] ?? STRINGS.en;
    const fallback = STRINGS.en;
    return (key, params) => {
        let value = table[key] ?? fallback[key] ?? key;
        if (params) {
            for (const [name, replacement] of Object.entries(params)) {
                value = value.replaceAll(`{${name}}`, String(replacement));
            }
        }
        return value;
    };
}
